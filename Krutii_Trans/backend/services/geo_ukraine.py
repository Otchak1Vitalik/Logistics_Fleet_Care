def haversine(a, b):
    """Відстань між точками (lat, lon) у км."""
    lat1, lon1, lat2, lon2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def bearing(a, b):
    """Напрямок руху в градусах (0 - північ, за годинниковою стрілкою)."""
    lat1, lat2 = math.radians(a[0]), math.radians(b[0])
    dlon = math.radians(b[1] - a[1])
    x = math.sin(dlon) * math.cos(lat2)
    y = math.cos(lat1) * math.sin(lat2) - math.sin(lat1) * math.cos(lat2) * math.cos(dlon)
    return (math.degrees(math.atan2(x, y)) + 360) % 360


def _graph():
    g = {c: [] for c in CITIES}
    for a, b in ROADS:
        d = haversine(CITIES[a], CITIES[b]) * ROAD_FACTOR
        g[a].append((b, d))
        g[b].append((a, d))
    return g


_G = _graph()


def route(origin, destination):
    """Міста маршруту від origin до destination (найкоротший шлях); None - якщо міста невідомі."""
    if origin not in CITIES or destination not in CITIES:
        return None
    if origin == destination:
        return [origin]
    dist, prev, heap = {origin: 0.0}, {}, [(0.0, origin)]
    while heap:
        d, c = heapq.heappop(heap)
        if c == destination:
            break
        if d > dist.get(c, math.inf):
            continue
        for n, w in _G[c]:
            if d + w < dist.get(n, math.inf):
                dist[n], prev[n] = d + w, c
                heapq.heappush(heap, (d + w, n))
    if destination not in dist:
        return None
    path = [destination]
    while path[-1] != origin:
        path.append(prev[path[-1]])
    return path[::-1]


def route_points(origin, destination):
    """Координати маршруту [[lat, lon], ...] і довжина в км."""
    cities = route(origin, destination)
    if not cities:
        return None, 0.0
    pts = [list(CITIES[c]) for c in cities]
    km = sum(haversine(pts[i], pts[i + 1]) * ROAD_FACTOR for i in range(len(pts) - 1))
    return pts, round(km, 1)


def nearest_city(lat, lon, max_km=25):
    best = min(CITIES.items(), key=lambda kv: haversine((lat, lon), kv[1]))
    return best[0] if haversine((lat, lon), best[1]) <= max_km else None
